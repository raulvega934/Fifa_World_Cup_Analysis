-- ------------------------------------------------------------
-- matches: one row per match (match_id = 1..104, chronological)
-- score is the original text; home/away_score are numeric.
-- home/away_penalties are only filled for penalty shoot-outs.
-- ------------------------------------------------------------
CREATE TABLE matches (
    match_id                                INTEGER PRIMARY KEY,
    stage                                   VARCHAR(25) NOT NULL,
    gameweek                                INTEGER,
    day_of_week                             VARCHAR(20),
    match_date                              DATE NOT NULL,
    start_time                              TIME,
    home_team_id                            INTEGER NOT NULL,
    away_team_id                            INTEGER NOT NULL,
    score                                   VARCHAR(20),
    home_score                              INTEGER,
    away_score                              INTEGER,
    home_penalties                          INTEGER,
    away_penalties                          INTEGER,
    attendance                              INTEGER,
    venue                                   VARCHAR(66),
    referee                                 VARCHAR(43),
    home_formation                          VARCHAR(20),
    away_formation                          VARCHAR(20),
    home_manager                            VARCHAR(28),
    away_manager                            VARCHAR(28),
    home_captain                            VARCHAR(25),
    away_captain                            VARCHAR(25),
    home_possession                         DECIMAL(8,2),
    away_possession                         DECIMAL(8,2),
    home_sot                                INTEGER,
    away_sot                                INTEGER,
    home_total_shots                        INTEGER,
    away_total_shots                        INTEGER,
    home_saves                              INTEGER,
    away_saves                              INTEGER,
    home_cards_yellow                       INTEGER,
    away_cards_yellow                       INTEGER,
    home_cards_red                          INTEGER,
    away_cards_red                          INTEGER,
    home_fouls                              INTEGER,
    away_fouls                              INTEGER,
    home_corners                            INTEGER,
    away_corners                            INTEGER,
    home_crosses                            INTEGER,
    away_crosses                            INTEGER,
    home_interceptions                      INTEGER,
    away_interceptions                      INTEGER,
    home_offsides                           INTEGER,
    away_offsides                           INTEGER,
    notes                                   VARCHAR(255),
    FOREIGN KEY (home_team_id) REFERENCES teams(team_id),
    FOREIGN KEY (away_team_id) REFERENCES teams(team_id),
    CHECK (home_team_id <> away_team_id)
);

-- Indexes on foreign keys / common filters
CREATE INDEX idx_players_team_id      ON players(team_id);
CREATE INDEX idx_players_position     ON players(position);
CREATE INDEX idx_matches_home_team_id ON matches(home_team_id);
CREATE INDEX idx_matches_away_team_id ON matches(away_team_id);
CREATE INDEX idx_matches_stage        ON matches(stage);
CREATE INDEX idx_matches_match_date   ON matches(match_date);